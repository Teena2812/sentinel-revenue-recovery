# Batch Generation (with second-pass tier computation)
# ---------------------------------------------------------------------------

def generate_full_batch() -> dict[str, list]:
    """Generate the full synthetic data batch.

    IMPORTANT: Relationship tiers are computed in a SECOND PASS after all
    cases exist, because value percentile (V) requires the full portfolio
    of amounts. Computing per-case during generation would quietly break
    every tier assignment by evaluating percentiles against a partial batch.
    """
    print("Generating synthetic data batch (ALL DATA IS SIMULATED)...")

    # Step 1: Generate raw cases (no tiers yet)
    payment_cases = _generate_failed_payments(30)
    b2b_cases = _generate_b2b_receivables(50)

    # Step 2: Compute relationship tiers in a SECOND PASS
    # Payment and B2B tiers are computed within their own scenario pools,
    # since value percentile is only meaningful within the same case type.
    print(f"  Computing relationship tiers for {len(payment_cases)} payment cases...")
    payment_results = compute_tiers_for_batch(payment_cases)

    print(f"  Computing relationship tiers for {len(b2b_cases)} B2B cases...")
    b2b_results = compute_tiers_for_batch(b2b_cases)

    # Step 3: Report distribution
    _report_distribution("Failed Payments", payment_cases, payment_results)
    _report_distribution("B2B Receivables", b2b_cases, b2b_results)

    return {
        "failed_payments": payment_cases,
        "b2b_receivables": b2b_cases,
    }


def _report_distribution(label: str, cases: list, results: list) -> None:
    """Print a summary of the generated batch for verification."""
    print(f"\n  --- {label} ({len(cases)} cases) ---")

    # Amount range
    amounts = [c.amount for c in cases]
    print(f"  Amount range: ₹{min(amounts):,.2f} – ₹{max(amounts):,.2f}")

    # Tier distribution
    tiers = {}
    for case, _, _ in results:
        tier = case.relationship_tier.value if case.relationship_tier else "NONE"
        tiers[tier] = tiers.get(tier, 0) + 1
    print(f"  Tier distribution: {tiers}")

    # Special cases
    if hasattr(cases[0], "failure_code"):
        fraud_count = sum(1 for c in cases if c.fraud_flag)
        low_value_count = sum(1 for c in cases if c.amount < 500)
        at_cap = sum(1 for c in cases if c.attempt_count >= 5)
        conflict_count = sum(1 for c in cases if c.conflicting_signals)
        print(f"  Fraud-flagged: {fraud_count}")
        print(f"  Below ₹500 threshold: {low_value_count}")
        print(f"  At attempt cap (5): {at_cap}")
        print(f"  With conflicting signals: {conflict_count}")
    else:
        dispute_count = sum(1 for c in cases if c.dispute_flag)
        fraud_count = sum(1 for c in cases if c.fraud_flag)
        low_value_count = sum(1 for c in cases if c.amount < 5000)
        promise_count = sum(1 for c in cases if c.promise_to_pay)
        broken = sum(1 for c in cases if c.promise_to_pay and c.promise_to_pay.kept is False)
        conflict_count = sum(1 for c in cases if c.conflicting_signals)
        print(f"  Disputed: {dispute_count}")
        print(f"  Fraud-flagged: {fraud_count}")
        print(f"  Below ₹5,000 threshold: {low_value_count}")
        print(f"  With promise-to-pay: {promise_count} (broken: {broken})")
        print(f"  With conflicting signals: {conflict_count}")


def save_batch(batch: dict[str, list], output_dir: str | None = None) -> dict[str, str]:
    """Save the generated batch to JSON files.

    Returns a dict of {scenario_name: file_path}.
    """
    out_dir = output_dir or DATA_DIR
    os.makedirs(out_dir, exist_ok=True)
    paths = {}

    for scenario_name, cases in batch.items():
        file_path = os.path.join(out_dir, f"{scenario_name}.json")
        data = {
            "data_type": "SIMULATED",
            "generated_at": datetime.now().isoformat(),
            "description": (
                "Synthetic data for the AI Revenue Recovery Agent. "
                "ALL DATA IS SIMULATED — never imply real Razorpay data."
            ),
            "count": len(cases),
            "cases": [case_to_dict(c) for c in cases],
        }
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, default=str)
        print(f"  Saved {len(cases)} cases to {file_path}")
        paths[scenario_name] = file_path

    return paths


def generate_all(output_dir: str | None = None) -> dict[str, str]:
    """Generate and save all synthetic datasets to disk (anchored to SIMULATED_CURRENT_TIME)."""
    batch = generate_full_batch()
    return save_batch(batch, output_dir=output_dir)


