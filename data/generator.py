"""
Synthetic Data Generator — creates realistic batches of simulated cases.

ALL DATA GENERATED BY THIS MODULE IS SIMULATED.
Never imply it is real Razorpay data.

Generates:
- ~30 failed payment cases with realistic failure-code distributions
- ~50 B2B receivable cases with varied histories, disputes, and relationship profiles

Key design choices:
- Relationship tiers are computed in a SECOND PASS after the full batch is
  generated, because value percentile (V) requires all amounts to exist first.
  (Confirmed requirement — computing per-case during generation would silently
  break every tier assignment.)
- 2–3 failed payment cases below ₹500 for cost-threshold testing
- 2–3 B2B cases below ₹5,000 for B2B cost-threshold testing
- ~5 B2B cases with dispute_flag=True
- ~3 B2B cases with broken promise-to-pay
- 2 cases with conflicting_signals for Stress Test scenario 8
- ~3 fraud-flagged payment cases
- A handful of cases at attempt cap for boundary testing

Output: JSON files in data/ directory with "data_type": "SIMULATED" metadata.
"""

from __future__ import annotations

import json
import os
import random
import uuid
from datetime import datetime, timedelta
from typing import Any

from core import config
from core.relationship import compute_tiers_for_batch
from core.schemas import (
    B2BReceivableCase,
    ConflictingSignal,
    CustomerHistory,
    FailedPaymentCase,
    FailureCode,
    PromiseToPay,
    case_to_dict,
)

# Reproducible randomness for consistent synthetic data
SEED = 42
_rng = random.Random(SEED)

# Output directory
DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)))


def _uuid() -> str:
    """Generate a deterministic-looking UUID from our seeded RNG."""
    return str(uuid.UUID(int=_rng.getrandbits(128), version=4))


def _random_datetime(start: datetime, end: datetime) -> datetime:
    """Random datetime between start and end."""
    delta = end - start
    random_seconds = _rng.randint(0, int(delta.total_seconds()))
    return start + timedelta(seconds=random_seconds)


# ---------------------------------------------------------------------------
# Failed Payment Case Generator
# ---------------------------------------------------------------------------

def _generate_failed_payments(count: int = 30) -> list[FailedPaymentCase]:
    """Generate ~30 failed payment cases with realistic distributions."""
    cases: list[FailedPaymentCase] = []
    ref_now = config.SIMULATED_CURRENT_TIME

    # Failure code distribution: ~35% insufficient, ~25% timeout, ~20% auth,
    # ~10% gateway, ~10% fraud
    failure_weights = [
        (FailureCode.INSUFFICIENT_FUNDS, 35),
        (FailureCode.BANK_TIMEOUT, 25),
        (FailureCode.AUTH_FAILURE, 20),
        (FailureCode.GATEWAY_ERROR, 10),
        (FailureCode.FRAUD_REJECTION, 10),
    ]
    failure_codes = []
    for code, weight in failure_weights:
        failure_codes.extend([code] * weight)

    # Amount ranges (skewed toward smaller)
    def _random_amount(low_value: bool = False) -> float:
        if low_value:
            return round(_rng.uniform(50, 450), 2)   # Below ₹500 threshold
        r = _rng.random()
        if r < 0.50:
            return round(_rng.uniform(500, 5000), 2)       # Small
        elif r < 0.80:
            return round(_rng.uniform(5000, 25000), 2)     # Medium
        elif r < 0.95:
            return round(_rng.uniform(25000, 50000), 2)    # Large
        else:
            return round(_rng.uniform(50000, 200000), 2)   # Very large

    # Generate 30 customer IDs (some customers have multiple failures)
    customer_pool_size = 22
    customer_ids = [f"CUST-{_uuid()[:8]}" for _ in range(customer_pool_size)]

    for i in range(count):
        # 2–3 below cost threshold
        low_value = i < 3
        amount = _random_amount(low_value=low_value)

        # Failure code
        failure_code = _rng.choice(failure_codes)

        # Fraud flag: always True for FRAUD_REJECTION, occasionally for others
        fraud_flag = failure_code == FailureCode.FRAUD_REJECTION
        if not fraud_flag and _rng.random() < 0.02:
            fraud_flag = True

        # Attempt count: mostly 1, some higher, a few at boundary
        if i < 2:
            attempt_count = 5  # At cap — for boundary testing
        elif _rng.random() < 0.3:
            attempt_count = _rng.randint(2, 4)
        else:
            attempt_count = 1

        # Customer history
        customer_id = _rng.choice(customer_ids)
        has_history = _rng.random() > 0.2  # 80% have history
        if has_history:
            reliability = round(_rng.uniform(0.2, 1.0), 2)
            transactions = _rng.randint(1, 80)
            total_amount = round(_rng.uniform(1000, 500000), 2)
        else:
            reliability = 0.5  # cold-start default
            transactions = 0
            total_amount = 0.0

        history = CustomerHistory(
            reliability_ratio=reliability,
            total_transactions=transactions,
            total_amount=total_amount,
            has_history=has_history,
        )

        # Timestamp: within the last 7 days from simulation anchor
        timestamp = _random_datetime(ref_now - timedelta(days=7), ref_now)

        # Conflicting signals: add to 1 payment case (scenario 8)
        conflicting_signals = []
        if i == 15:  # One specific case gets conflicting signals
            conflicting_signals = [
                ConflictingSignal(
                    source_a="risk_score_engine",
                    signal_a="safe_to_retry",
                    source_b="customer_support_ticket",
                    signal_b="customer_requested_stop_contact",
                    description="Risk engine marks this as safe to retry, but an "
                                "open support ticket shows the customer explicitly "
                                "asked to stop contact.",
                )
            ]

        case = FailedPaymentCase(
            case_id=f"PAY-{_uuid()[:12]}",
            amount=amount,
            failure_code=failure_code,
            timestamp=timestamp,
            attempt_count=attempt_count,
            customer_id=customer_id,
            customer_history=history,
            fraud_flag=fraud_flag,
            conflicting_signals=conflicting_signals,
            created_at=timestamp,
        )
        cases.append(case)

    return cases


