def _generate_b2b_receivables(count: int = 50) -> list[B2BReceivableCase]:
    """Generate ~50 B2B receivable cases with realistic distributions."""
    cases: list[B2BReceivableCase] = []
    ref_now = config.SIMULATED_CURRENT_TIME

    # Debtor pool (fewer debtors than cases — some debtors have multiple invoices)
    debtor_pool_size = 30
    debtor_ids = [f"DBT-{_uuid()[:8]}" for _ in range(debtor_pool_size)]

    # Amount ranges: ₹10,000–₹50,00,000 skewed toward mid-range
    # PLUS 2–3 below ₹5,000 for B2B cost-threshold testing
    def _random_b2b_amount(low_value: bool = False) -> float:
        if low_value:
            return round(_rng.uniform(1000, 4500), 2)  # Below ₹5,000 threshold
        r = _rng.random()
        if r < 0.40:
            return round(_rng.uniform(10000, 100000), 2)       # Small B2B
        elif r < 0.75:
            return round(_rng.uniform(100000, 500000), 2)      # Mid-range
        elif r < 0.92:
            return round(_rng.uniform(500000, 2000000), 2)     # Large
        else:
            return round(_rng.uniform(2000000, 5000000), 2)    # Very large

    for i in range(count):
        # 2–3 below B2B cost threshold
        low_value = i < 3
        amount = _random_b2b_amount(low_value=low_value)

        debtor_id = _rng.choice(debtor_ids)

        # Days overdue: 1–90, realistic distribution
        days_overdue = max(1, int(_rng.expovariate(1 / 25)))  # mean ~25 days
        days_overdue = min(days_overdue, 90)
        due_date = ref_now - timedelta(days=days_overdue)
        invoice_date = due_date - timedelta(days=_rng.randint(15, 45))

        # Debtor history
        has_history = _rng.random() > 0.15  # 85% have history
        if has_history:
            reliability = round(_rng.uniform(0.1, 1.0), 2)
            transactions = _rng.randint(1, 100)
            total_amount = round(_rng.uniform(50000, 5000000), 2)
        else:
            reliability = 0.5
            transactions = 0
            total_amount = 0.0

        history = CustomerHistory(
            reliability_ratio=reliability,
            total_transactions=transactions,
            total_amount=total_amount,
            has_history=has_history,
        )

        # Dispute flag: ~10% of cases
        dispute_flag = i < 5  # First 5 cases are disputed (ensures exactly 5)

        # Fraud flag: ~4% of B2B cases
        fraud_flag = i in (7, 8)  # 2 fraud-flagged cases

        # Attempt/contact count
        if _rng.random() < 0.2:
            attempt_count = _rng.randint(3, 4)  # At or near cap
            contact_count = _rng.randint(2, 4)
        else:
            attempt_count = _rng.randint(0, 2)
            contact_count = _rng.randint(0, 2)

        # Promise-to-pay: ~15% have one, ~3 of those are broken
        promise = None
        if 20 <= i < 28:  # 8 cases get promises
            promise_date = ref_now + timedelta(days=_rng.randint(-5, 15))
            kept = None
            if i < 23:
                # 3 broken promises (promise date in the past, not kept)
                promise_date = ref_now - timedelta(days=_rng.randint(1, 10))
                kept = False
            elif promise_date < ref_now:
                kept = True  # Past due and kept
            promise = PromiseToPay(
                promised_date=promise_date,
                promised_amount=amount,
                kept=kept,
            )

        # Conflicting signals: 1 B2B case (scenario 8)
        conflicting_signals = []
        if i == 35:
            conflicting_signals = [
                ConflictingSignal(
                    source_a="payment_history_analysis",
                    signal_a="debtor_likely_to_pay_soon",
                    source_b="credit_report_update",
                    signal_b="debtor_credit_rating_downgraded",
                    description="Payment history suggests the debtor is likely to "
                                "pay soon, but a recent credit report shows their "
                                "rating was downgraded — conflicting recovery outlook.",
                )
            ]

        case = B2BReceivableCase(
            case_id=f"B2B-{_uuid()[:12]}",
            invoice_id=f"INV-{_uuid()[:10]}",
            amount=amount,
            invoice_date=invoice_date,
            due_date=due_date,
            debtor_id=debtor_id,
            debtor_history=history,
            attempt_count=attempt_count,
            contact_count=contact_count,
            dispute_flag=dispute_flag,
            fraud_flag=fraud_flag,
            promise_to_pay=promise,
            conflicting_signals=conflicting_signals,
            created_at=invoice_date,
        )
        cases.append(case)

    return cases


